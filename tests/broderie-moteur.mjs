    if (v < 0) continue;
    const vois = [];
    if (y > 0) vois.push(L[(y - 1) * W + x]);
    if (y < H - 1) vois.push(L[(y + 1) * W + x]);
    if (x > 0) vois.push(L[y * W + x - 1]);
    if (x < W - 1) vois.push(L[y * W + x + 1]);
    if (vois.includes(v)) continue;
    const cpt = /* @__PURE__ */ new Map();
